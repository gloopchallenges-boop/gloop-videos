"""Gloop daily generator: picks today's arena + hazard combos, finds the best physics run for each by
headless seed search, renders it with the normal build (gloop_build.sh: video + sfx + voice + mix + size
check) and writes everything the Make.com scenario / TikTok posting need.

  python3 engine/gloop_daily.py                      # today (Europe/Warsaw), count from DAILY.md rules
  python3 engine/gloop_daily.py --count 3 --sample /tmp/samples --seed-base 100   # dry run, repo untouched

Writes (normal mode):  queue/<date>/vN.mp4, vN.json (title/description/pinnedComment), vN_tiktok.txt,
                       queue/<date>/meta.json (Make contract), engine/scenarios/<date>_vN.py,
                       history.md rows, engine/combo_history.json (no arena+hazard repeat within 14 days).
"""
import sys, os, json, random, subprocess, argparse, datetime, time
from zoneinfo import ZoneInfo
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(HERE); SC = os.path.join(HERE, 'scenarios')
sys.path.insert(0, SC)
import gloop_arena as G

TZ = ZoneInfo('Europe/Warsaw')
PINNED = 'What should Gloop survive next? 👇'
COMBO_FILE = os.path.join(HERE, 'combo_history.json')
NO_REPEAT_DAYS = 14

def day_count(d):
    if datetime.date(2026, 11, 1) <= d <= datetime.date(2026, 11, 14): return 8
    return 3
def post_times(d, n):
    if n >= 8: base = ['12:00', '13:00', '14:00', '16:00', '17:00', '18:00', '20:00', '21:00']
    elif d.weekday() >= 5: base = ['14:00', '18:00', '21:00']
    else: base = ['12:00', '18:00', '21:00']
    extra = ['16:00', '23:00', '22:00', '19:00', '15:00']
    return (base + extra)[:n]

def key(arena, hz): return arena + '|' + '+'.join(sorted(hz))
def load_hist():
    try: return json.load(open(COMBO_FILE))
    except (OSError, ValueError): return []

def pick_combos(d, n, rng, hist):
    cutoff = (d - datetime.timedelta(days=NO_REPEAT_DAYS)).isoformat()
    recent = {key(h['arena'], h['hazards']) for h in hist if h['date'] > cutoff}
    last = {}
    for h in hist:
        last[h['arena']] = max(last.get(h['arena'], ''), h['date'])
        for z in h['hazards']: last[z] = max(last.get(z, ''), h['date'])
    arenas = sorted(G.ARENAS, key=lambda a: (last.get(a, ''), rng.random()))
    used_hz = {}; out = []
    for i in range(n):
        a = arenas[i % len(arenas)]
        for _ in range(500):
            k2 = rng.random() < 0.5
            pool = sorted(G.HAZ, key=lambda z: (used_hz.get(z, 0), last.get(z, ''), rng.random()))
            hz = [pool[0]] if not k2 else [pool[0], rng.choice(pool[1:5])]
            rng.shuffle(hz)
            if len(hz) == 2 and any(set(hz) == c for c in G.INCOMPAT): continue
            kk = key(a, hz)
            if kk in recent or kk in {key(o['arena'], o['hazards']) for o in out}: continue
            break
        for z in hz: used_hz[z] = used_hz.get(z, 0) + 1
        out.append({'arena': a, 'hazards': hz})
    return out

def search(arena, hz, TL, want, seed_base, budget=1400, log=print):
    """Run the physics headless for many seeds x difficulties, keep the best-scoring run."""
    best = None; tried = 0; t0 = time.time(); Ds = [0.7, 0.85, 1.0, 1.15, 1.3]
    for seed in range(seed_base, seed_base + budget):
        D = Ds[seed % len(Ds)]
        st = G.World({'arena': arena, 'hazards': hz, 'seed': seed, 'TL': TL, 'D': D}).simulate().stats(); tried += 1
        sc = G.score(st, want, TL)
        if sc is not None and (best is None or sc > best[0]): best = (sc, st)
        if best and best[0] >= 10 and tried >= 120: break
    log(f'   search {arena} {hz} TL{TL} want {want}: {tried} runs in {time.time() - t0:.0f}s -> {best[1] if best else None}')
    return best[1] if best else None

def texts(arena, hz, TL):
    words = ' and '.join(G.HAZ[h][1] for h in hz)
    title = f'Can Gloop survive {TL} seconds of {words}?'
    if len(title) > 60: title = f'Can Gloop survive {TL}s of {words}?'
    if len(title) > 60: title = f'Can Gloop survive {TL}s of {G.HAZ[hz[0]][1]}?'
    line = f"Gloop vs {words} in {G.ARENAS[arena]['label']}: real bounce physics, and it speeds up every second."
    tags = ['#shorts', '#physics', '#simulation', '#satisfying', G.HAZ[hz[0]][3]]
    desc = line + '\n' + ' '.join(tags)
    tiktok = title + '\n\n' + ' '.join(['#gloop', '#physics', '#simulation', '#satisfying', G.HAZ[hz[0]][3]])
    say = ' and '.join(G.HAZ[h][0] if i == 0 else G.HAZ[h][0].replace('the ', '', 1) for i, h in enumerate(hz))
    return title, desc, tiktok, say

SCEN_TMPL = '''"""{date} v{i} - Gloop ARENA video (generated by engine/gloop_daily.py): {arena} + {hz}.
Run picked by headless seed search: {stats}"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))){extra}
from gloop_arena import main

SAY = '{say}'
CFG = {cfg}
if __name__ == '__main__':
    main(CFG)
'''

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--date'); ap.add_argument('--count', type=int); ap.add_argument('--sample')
    ap.add_argument('--seed-base', type=int); ap.add_argument('--jobs', type=int, default=2)
    ap.add_argument('--combos', help='json list of {arena,hazards[,want,TL]} to force (testing)')
    a = ap.parse_args()
    d = datetime.date.fromisoformat(a.date) if a.date else datetime.datetime.now(TZ).date()
    ds = d.isoformat(); sample = a.sample
    qdir = sample or os.path.join(REPO, 'queue', ds); os.makedirs(qdir, exist_ok=True)
    meta_p = os.path.join(qdir, 'meta.json')
    old = json.load(open(meta_p))['videos'] if (os.path.exists(meta_p) and not sample) else []   # carry-over stays untouched
    n_total = a.count or day_count(d); n_new = max(0, n_total - len(old))
    rng = random.Random(int(d.strftime('%Y%m%d')) * 7 + (a.seed_base or 0))
    hist = load_hist()
    combos = json.loads(a.combos) if a.combos else pick_combos(d, n_new, rng, hist)
    n_new = len(combos)
    wins = round(n_new * 0.6); wants = ['win'] * wins + ['fail'] * (n_new - wins); rng.shuffle(wants)
    times = post_times(d, len(old) + n_new)
    scen_dir = os.path.join(sample, 'scenarios') if sample else SC; os.makedirs(scen_dir, exist_ok=True)
    jobs = []
    for j, cb in enumerate(combos):
        i = len(old) + j + 1; arena, hz = cb['arena'], cb['hazards']
        TL = cb.get('TL') or rng.randint(12, 16); want = cb.get('want') or wants[j]
        sb = (a.seed_base if a.seed_base is not None else int(d.strftime('%m%d')) * 1000) + j * 2000
        st = search(arena, hz, TL, want, sb)
        if st is None:
            want = 'fail' if want == 'win' else 'win'; st = search(arena, hz, TL, want, sb + 5000)
        if st is None: print(f'!! v{i}: no acceptable run for {arena} {hz}, skipped'); continue
        title, desc, tiktok, say = texts(arena, hz, TL)
        cfg = {'arena': arena, 'hazards': hz, 'seed': st['seed'], 'TL': TL, 'D': st['D']}
        sp = os.path.join(scen_dir, f'{ds}_v{i}.py')
        open(sp, 'w').write(SCEN_TMPL.format(date=ds, i=i, arena=arena, hz='+'.join(hz), stats=json.dumps(st), say=say, cfg=json.dumps(cfg), extra=(f'\nsys.path.insert(0, {SC!r})' if sample else '')))
        jobs.append(dict(i=i, sp=sp, st=st, title=title, desc=desc, tiktok=tiktok, cfg=cfg, at=times[i - 1]))
    # render (2 at a time on the 2 cores)
    procs = []
    for jb in jobs:
        out = os.path.join(qdir, f"v{jb['i']}.mp4")
        procs.append((jb, subprocess.Popen(['bash', os.path.join(SC, 'gloop_build.sh'), jb['sp'], out], stdout=subprocess.PIPE, stderr=subprocess.STDOUT)))
        while sum(p.poll() is None for _, p in procs) >= a.jobs: time.sleep(2)
    off = datetime.datetime.combine(d, datetime.time(12), TZ).strftime('%z'); off = off[:3] + ':' + off[3:]
    new_meta = []
    for jb, p in procs:
        o = p.communicate()[0].decode()[-400:]; ok = p.returncode == 0 and os.path.exists(os.path.join(qdir, f"v{jb['i']}.mp4"))
        print(f"v{jb['i']}: {'OK' if ok else 'BUILD FAILED'} {o.strip().splitlines()[-1] if o.strip() else ''}")
        if not ok: continue
        m = {'file': f"v{jb['i']}.mp4", 'title': jb['title'], 'description': jb['desc'], 'pinnedComment': PINNED,
             'publishAt': f"{ds}T{jb['at']}:00{off}"}
        new_meta.append(m)
        json.dump(m, open(os.path.join(qdir, f"v{jb['i']}.json"), 'w'), indent=1, ensure_ascii=False)
        open(os.path.join(qdir, f"v{jb['i']}_tiktok.txt"), 'w').write(jb['tiktok'] + '\n')
        if not sample:
            st = jb['st']; c = jb['cfg']
            res = (f"Survived ({st['hearts']} heart{'s' if st['hearts'] != 1 else ''} left, {st['nears']} close calls)" if st['outcome'] == 'win'
                   else f"Failed (last heart lost {st['t_fail']}s in, {st['nears']} close calls, claw collected)")
            row = (f"| {ds} | {jb['title']} | {' + '.join(c['hazards'])} in {c['arena']} (seed {c['seed']}, D {c['D']}) | "
                   f"ARENA – HEARTS ❤❤❤ | Bouncing in {G.ARENAS[c['arena']]['label']} | {res} |")
            hp = os.path.join(REPO, 'history.md'); h = open(hp).read().rstrip('\n') + '\n' + row + '\n'; open(hp, 'w').write(h)
            hist.append({'date': ds, 'arena': c['arena'], 'hazards': c['hazards'], 'file': m['file']})
    meta = {'videos': old + new_meta}
    json.dump(meta, open(meta_p, 'w'), indent=1, ensure_ascii=False)
    if not sample:
        import shutil
        for q in os.listdir(os.path.join(REPO, 'queue')):   # keep the repo small: drop queue days older than 3 days
            try:
                if datetime.date.fromisoformat(q) < d - datetime.timedelta(days=3): shutil.rmtree(os.path.join(REPO, 'queue', q))
            except ValueError: pass
        cutoff = (d - datetime.timedelta(days=60)).isoformat()
        json.dump([h for h in hist if h['date'] > cutoff], open(COMBO_FILE, 'w'), indent=1)
    print(f'{len(new_meta)} new videos in {meta_p}')

if __name__ == '__main__':
    main()
